import { useEffect, useState } from "react";
import axios from "axios";
import {
  History,
  FileText,
  Trash2,
  Eye,
  RefreshCw,
  Sprout,
  CalendarDays,
  X,
  AlertCircle
} from "lucide-react";

const API = (import.meta.env.VITE_API_URL || "http://127.0.0.1:8000").replace(/\/$/, "");

export default function HistoryPanel() {
  const [history, setHistory] = useState([]);
  const [selectedReport, setSelectedReport] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [deletingId, setDeletingId] = useState(null);

  const loadHistory = async () => {
    setLoading(true);
    setError("");

    try {
      const response = await axios.get(`${API}/history`);
      setHistory(response.data.history || []);
    } catch (err) {
      setError(
        err.response?.data?.detail ||
        "Unable to load saved reports."
      );
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadHistory();
  }, []);

  const openReport = async (id) => {
    setError("");

    try {
      const response = await axios.get(`${API}/history/${id}`);
      setSelectedReport(response.data);
    } catch (err) {
      setError(
        err.response?.data?.detail ||
        "Unable to open this report."
      );
    }
  };

  const deleteReport = async (id) => {
    const confirmed = window.confirm(
      "Are you sure you want to delete this saved report?"
    );

    if (!confirmed) return;

    setDeletingId(id);
    setError("");

    try {
      await axios.delete(`${API}/history/${id}`);
      setHistory((previous) =>
        previous.filter((item) => item.id !== id)
      );

      if (selectedReport?.id === id) {
        setSelectedReport(null);
      }
    } catch (err) {
      setError(
        err.response?.data?.detail ||
        "Unable to delete this report."
      );
    } finally {
      setDeletingId(null);
    }
  };

  const renameReport = async (id, currentName) => {
    const newName = window.prompt(
      "Enter a new farm/report name:",
      currentName
    );

    if (newName === null) return;

    if (!newName.trim()) {
      window.alert("Farm name cannot be empty.");
      return;
    }

    try {
      await axios.patch(`${API}/history/${id}/rename`, {
        farm_name: newName.trim()
      });

      setHistory((previous) =>
        previous.map((item) =>
          item.id === id
            ? { ...item, farm_name: newName.trim() }
            : item
        )
      );

      setSelectedReport((previous) =>
        previous?.id === id
          ? { ...previous, farm_name: newName.trim() }
          : previous
      );
    } catch (err) {
      setError(
        err.response?.data?.detail ||
        "Unable to rename this report."
      );
    }
  };

  const formatDate = (date) => {
    return new Date(date).toLocaleString();
  };

  const downloadReport = (format) => {
    if (!selectedReport) return;

    const analysis = selectedReport.analysis || {};

    const reportData = {
      farm_name: selectedReport.farm_name,
      saved_at: selectedReport.created_at,
      analysis: analysis
    };

    let content;
    let mimeType;
    let extension;

    if (format === "json") {
      content = JSON.stringify(reportData, null, 2);
      mimeType = "application/json";
      extension = "json";
    } else {
      content = [
        "AGRIMIND AI - FARM ANALYSIS REPORT",
        "===================================",
        "",
        `Farm Name: ${selectedReport.farm_name}`,
        `Saved At: ${formatDate(selectedReport.created_at)}`,
        "",
        "ANALYSIS DETAILS",
        "----------------",
        JSON.stringify(analysis, null, 2),
        "",
        "Generated by AgriMind AI - Prolog-powered Agricultural Expert System",
        "Note: Recommendations are general guidance. Verify local agricultural conditions."
      ].join("\\n");

      mimeType = "text/plain";
      extension = "txt";
    }

    const blob = new Blob([content], { type: `${mimeType};charset=utf-8` });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");

    const safeName = selectedReport.farm_name
      .replace(/[^a-z0-9-_]/gi, "_");

    link.href = url;
    link.download = `AgriMind_${safeName}_${selectedReport.id}.${extension}`;

    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);

    URL.revokeObjectURL(url);
  };

  return (
    <section className="history-panel" id="analysis-history">
      <div className="history-heading">
        <div>
          <span className="history-eyebrow">YOUR FARM RECORDS</span>
          <h2><History size={23} /> Analysis History</h2>
          <p>Access and manage your previously saved farm analyses.</p>
        </div>

        <button
          type="button"
          className="history-refresh"
          onClick={loadHistory}
          disabled={loading}
        >
          <RefreshCw size={16} className={loading ? "history-spin" : ""} />
          Refresh
        </button>
      </div>

      {error && (
        <div className="history-error">
          <AlertCircle size={17} />
          {error}
        </div>
      )}

      {selectedReport && (
        <div className="history-detail">
          <div className="history-detail-heading">
            <div>
              <span className="history-eyebrow">SAVED FARM REPORT</span>
              <h3>{selectedReport.farm_name}</h3>
              <small>{formatDate(selectedReport.created_at)}</small>
            </div>

            <button
              type="button"
              className="history-close"
              onClick={() => setSelectedReport(null)}
              aria-label="Close report"
            >
              <X size={19} />
            </button>
          </div>

          <div className="history-download-actions">
            <button
              type="button"
              onClick={() => downloadReport("txt")}
            >
              <FileText size={16} /> Download TXT
            </button>

            <button
              type="button"
              onClick={() => downloadReport("json")}
            >
              <FileText size={16} /> Download JSON
            </button>
          </div>

          <div className="history-report-content">
            <h4>Farm Analysis Details</h4>
            <pre>{JSON.stringify(selectedReport.analysis, null, 2)}</pre>
          </div>
        </div>
      )}

      <div className="history-list-heading">
        <h3>Saved Analyses</h3>
        <span>{history.length} reports</span>
      </div>

      {loading && history.length === 0 ? (
        <div className="history-empty">
          <RefreshCw size={25} className="history-spin" />
          <p>Loading analysis history...</p>
        </div>
      ) : history.length === 0 ? (
        <div className="history-empty">
          <FileText size={35} />
          <h3>No saved reports yet</h3>
          <p>Your saved farm analyses will appear here.</p>
        </div>
      ) : (
        <div className="history-record-list">
          {history.map((record) => (
            <article className="history-record" key={record.id}>
              <div className="history-record-icon">
                <Sprout size={21} />
              </div>

              <div className="history-record-info">
                <h4>{record.farm_name}</h4>
                <span>
                  <CalendarDays size={13} />
                  {formatDate(record.created_at)}
                </span>
                <p>
                  Best crop: <strong>{
                    typeof record.best_crop === "object"
                      ? record.best_crop?.crop || "Not available"
                      : record.best_crop || "Not available"
                  }</strong>
                </p>
              </div>

              <div className="history-record-actions">
                <button
                  type="button"
                  onClick={() => openReport(record.id)}
                  title="View report"
                  aria-label="View report"
                >
                  <Eye size={17} />
                </button>

                <button
                  type="button"
                  onClick={() => renameReport(record.id, record.farm_name)}
                  title="Rename report"
                  aria-label="Rename report"
                >
                  Rename
                </button>

                <button
                  type="button"
                  onClick={() => deleteReport(record.id)}
                  disabled={deletingId === record.id}
                  title="Delete report"
                  aria-label="Delete report"
                  className="history-delete"
                >
                  <Trash2 size={17} />
                </button>
              </div>
            </article>
          ))}
        </div>
      )}
    </section>
  );
}
